import type { FormField, FormSchema } from "@/lib/form-engine"
import { formatValue, isInputField } from "@/lib/form-engine"

export interface ReceiptData {
  formTitle: string
  formDescription?: string | null
  submissionId: string
  createdAt: Date
  score: number | null
  status: string
  schema: FormSchema
  /** Submission data keyed by field.key */
  data: Record<string, unknown>
  brandColor?: string
}

function rowsFor(schema: FormSchema, data: Record<string, unknown>) {
  const rows: { field: FormField; value: string }[] = []
  for (const f of schema.fields) {
    if (!isInputField(f) || f.type === "password" || f.type === "hidden") continue
    if (!(f.key in data)) continue
    const raw = data[f.key]
    let value: string
    if (f.type === "file") value = raw && typeof raw === "object" && "name" in (raw as object) ? String((raw as { name: unknown }).name) : formatValue(f, raw as never)
    else if (f.type === "signature") value = raw ? "Signed" : "—"
    else value = formatValue(f, raw as never)
    rows.push({ field: f, value: value || "—" })
  }
  return rows
}

/** Print-optimised A4 receipt. Pure server component — no client JS. */
export function ReceiptDocument({ receipt }: { receipt: ReceiptData }) {
  const rows = rowsFor(receipt.schema, receipt.data)
  const accent = receipt.brandColor || "#111111"
  return (
    <article className="fs-print receipt-sheet mx-auto bg-white text-[13px] leading-relaxed text-neutral-900">
      <header className="flex items-start justify-between gap-6 border-b border-neutral-200 pb-5" style={{ borderTop: `3px solid ${accent}`, paddingTop: 20 }}>
        <div className="min-w-0">
          <p className="text-[11px] font-medium tracking-wide text-neutral-500 uppercase">Submission receipt</p>
          <h1 className="mt-1 text-xl font-semibold tracking-tight">{receipt.formTitle}</h1>
          {receipt.formDescription && <p className="mt-1 text-neutral-600">{receipt.formDescription}</p>}
        </div>
        <dl className="shrink-0 space-y-1 text-right text-[11px] text-neutral-500">
          <div>
            <dt className="inline">Receipt </dt>
            <dd className="inline font-mono text-neutral-900 tabular-nums">{receipt.submissionId}</dd>
          </div>
          <div>
            <dt className="inline">Submitted </dt>
            <dd className="inline font-mono text-neutral-900 tabular-nums">
              {receipt.createdAt.toISOString().replace("T", " ").slice(0, 16)} UTC
            </dd>
          </div>
          {receipt.score !== null && (
            <div>
              <dt className="inline">Score </dt>
              <dd className="inline font-mono text-neutral-900 tabular-nums">{receipt.score}</dd>
            </div>
          )}
        </dl>
      </header>
      <table className="mt-4 w-full border-collapse">
        <tbody>
          {rows.map(({ field, value }) => (
            <tr key={field.id} className="receipt-row border-b border-neutral-100 align-top">
              <th scope="row" className="w-[38%] py-2.5 pr-4 text-left font-medium text-neutral-500">
                {field.label}
              </th>
              <td className="py-2.5 break-words whitespace-pre-wrap">{value}</td>
            </tr>
          ))}
          {rows.length === 0 && (
            <tr>
              <td className="py-6 text-center text-neutral-500" colSpan={2}>
                No answers recorded.
              </td>
            </tr>
          )}
        </tbody>
      </table>
      <footer className="mt-8 flex items-center justify-between border-t border-neutral-200 pt-3 text-[11px] text-neutral-500">
        <span>Generated by Digital Fueled</span>
        <span className="font-mono tabular-nums">{rows.length} answers</span>
      </footer>
    </article>
  )
}
